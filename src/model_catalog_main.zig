//! Host-only generator; the parser itself has no I/O.
const std = @import("std");
const models_dev = @import("models_dev.zig");
const model_capability = @import("model_capability.zig");

pub fn main(init: std.process.Init) !void {
    const scratch = init.arena.allocator();
    const args = try init.minimal.args.toSlice(scratch);
    // The build supplies the output path; the user supplies the input path.
    if (args.len != 3) {
        try std.Io.File.stderr().writeStreamingAll(init.io, "usage: zig build model-catalog -- <path to api.json>\n");
        std.process.exit(1);
    }
    const body = try std.Io.Dir.cwd().readFileAlloc(init.io, args[2], scratch, .unlimited);
    const entries = try models_dev.parse(scratch, body);
    var output: std.Io.Writer.Allocating = .init(scratch);
    const out = &output.writer;
    try out.writeAll(
        "// Generated by zig build model-catalog -- <path to api.json>; do not edit by hand.\n" ++
            "// The entry type is supplied by model_catalog.zig to keep imports one-way.\n" ++
            "pub fn entries(comptime Entry: type) []const Entry {\n",
    );
    // EnumSet.init evaluates each field of each generated row at comptime.
    try out.print("    @setEvalBranchQuota({d});\n", .{32 * entries.len + 1000});
    try out.writeAll("    return &.{\n");
    for (entries) |entry| {
        try out.print("        .{{ .id = \"{f}\", .context_window = ", .{std.zig.fmtString(entry.id)});
        if (entry.context_window) |context| try out.print("{d}", .{context}) else try out.writeAll("null");
        try out.writeAll(", .efforts = .init(.{");
        var first = true;
        for (std.enums.values(model_capability.ReasoningEffort)) |effort| {
            if (!entry.efforts.contains(effort)) continue;
            try out.print("{s} .{s} = true", .{ if (first) "" else ",", @tagName(effort) });
            first = false;
        }
        if (!first) try out.writeByte(' ');
        try out.print("}}), .openai_listed = {} }},\n", .{entry.openai_listed});
    }
    try out.writeAll("    };\n}\n");
    try std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = args[1], .data = output.written() });
}
