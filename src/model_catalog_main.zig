//! Host-only generator; the parser itself has no I/O.
const std = @import("std");
const models_dev = @import("models_dev.zig");
const catalog = @import("model_catalog.zig");
const model_capability = @import("model_capability.zig");

pub fn main(init: std.process.Init) !void {
    const scratch = init.arena.allocator();
    const args = try init.minimal.args.toSlice(scratch);
    // The build supplies the output path; the user supplies the input path.
    if (args.len != 3) {
        try std.Io.File.stderr().writeStreamingAll(init.io, "usage: zig build model-catalog -- <path to api.json>\n");
        std.process.exit(1);
    }
    const body = try std.Io.Dir.cwd().readFileAlloc(init.io, args[2], scratch, .unlimited);
    var output: std.Io.Writer.Allocating = .init(scratch);
    try writeSnapshot(scratch, &output.writer, std.fs.path.basename(args[2]), body);
    try std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = args[1], .data = output.written() });
}

/// Pure generation, including chat facts, from one coherent parsed catalog.
/// Only the writer's output survives; temporary metadata is released here.
fn writeSnapshot(scratch: std.mem.Allocator, out: *std.Io.Writer, source_name: []const u8, body: []const u8) !void {
    const records = try models_dev.parseForGeneration(scratch, body);
    defer scratch.free(records);
    defer for (records) |record| record.deinit(scratch);
    try out.writeAll(
        "// Generated by zig build model-catalog -- <path to api.json>; do not edit by hand.\n" ++
            "// The entry type is supplied by model_catalog.zig to keep imports one-way.\n" ++
            "pub fn entries(comptime Entry: type) []const Entry {\n",
    );
    // EnumSet.init evaluates each field of each generated row at comptime.
    try out.print("    @setEvalBranchQuota({d});\n", .{32 * records.len + 1000});
    try out.writeAll("    return &.{\n");
    for (records) |record| {
        const entry = record.model;
        try out.print("        .{{ .id = \"{f}\", .context_window = ", .{std.zig.fmtString(entry.id)});
        if (entry.context_window) |context| try out.print("{d}", .{context}) else try out.writeAll("null");
        try out.writeAll(", .efforts = .init(.{");
        var first = true;
        for (std.enums.values(model_capability.ReasoningEffort)) |effort| {
            if (!entry.efforts.contains(effort)) continue;
            try out.print("{s} .{s} = true", .{ if (first) "" else ",", @tagName(effort) });
            first = false;
        }
        if (!first) try out.writeByte(' ');
        try out.print("}}), .openai_listed = {} }},\n", .{entry.openai_listed});
    }
    try out.writeAll("    };\n}\n");
    try writeChatProjection(scratch, out, source_name, body, records);
}

fn writeChatProjection(scratch: std.mem.Allocator, out: *std.Io.Writer, source_name: []const u8, body: []const u8, records: []const models_dev.Generated) !void {
    var digest: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(body, &digest, .{});
    try out.print("\n// Generated projection of {f}; same ID precedence as models_dev.zig.\n// Source SHA-256: {s}\n", .{ std.zig.fmtString(source_name), &std.fmt.bytesToHex(digest, .lower) });
    try out.writeAll(
        "// Non-chat: explicit type other than chat, or no text input or no text output.\n" ++
            "// Families: declared family or ID through its type token, only when every shipped\n" ++
            "// ID at that hyphen-delimited prefix is non-chat. No inferred arbitrary ID stems.\n" ++
            "pub const non_chat_ids = [_][]const u8{\n",
    );
    var families: std.StringHashMap(void) = .init(scratch);
    defer families.deinit();
    for (records) |record| {
        if (record.canChat()) continue;
        const id = record.model.id;
        try out.print("    \"{f}\",\n", .{std.zig.fmtString(id)});
        const namespace = if (std.mem.lastIndexOfScalar(u8, id, '/')) |slash| slash + 1 else 0;
        const base = id[namespace..];
        if (record.family) |family| {
            if (family.len != 0 and base.len > family.len and base[family.len] == '-' and std.mem.startsWith(u8, base, family))
                try addFamily(&families, records, id[0 .. namespace + family.len]);
        }
        if (record.kind) |kind| {
            if (kind.len == 0) continue;
            var tokens = std.mem.splitScalar(u8, base, '-');
            var end = namespace;
            while (tokens.next()) |token| {
                end += token.len;
                if (std.mem.eql(u8, token, kind)) {
                    try addFamily(&families, records, id[0..end]);
                    break;
                }
                end += 1;
            }
        }
    }
    try out.writeAll("};\npub const non_chat_families = [_][]const u8{\n");
    const prefixes = try scratch.alloc([]const u8, families.count());
    defer scratch.free(prefixes);
    var keys = families.keyIterator();
    for (prefixes) |*prefix| prefix.* = keys.next().?.*;
    std.mem.sortUnstable([]const u8, prefixes, {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.order(u8, a, b) == .lt;
        }
    }.lessThan);
    for (prefixes) |prefix| try out.print("    \"{f}\",\n", .{std.zig.fmtString(prefix)});
    try out.writeAll("};\n");
}

/// Candidate slices borrow IDs from records, which outlive the family map.
/// A chat sibling disqualifies a whole-family inference, not its exact IDs.
fn addFamily(families: *std.StringHashMap(void), records: []const models_dev.Generated, prefix: []const u8) !void {
    for (records) |record| {
        if (record.canChat() and catalog.inFamily(record.model.id, prefix)) return;
    }
    try families.put(prefix, {});
}

const test_catalog =
    \\{"earlier":{"models":{
    \\  "gpt-image-next":{"type":"chat","family":"gpt-image","modalities":{"input":["text"],"output":["text"]}}
    \\}},"openai":{"models":{
    \\  "gpt-image-2":{"type":"image","family":"gpt-image","modalities":{"input":["text"],"output":["text","image"]}},
    \\  "text-embedding-1":{"type":"embedding","family":"text-embedding","modalities":{"input":["text"],"output":["text"]}},
    \\  "gpt-4.1":{"modalities":{"input":["text"],"output":["text"]}},
    \\  "gpt-realtime-1":{"type":"realtime","family":"gpt","modalities":{"input":["text","audio"],"output":["text","audio"]}}
    \\}}}
;

test "model catalog generator emits chat projection without excluding a chat sibling" {
    var output: std.Io.Writer.Allocating = .init(std.testing.allocator);
    defer output.deinit();
    try writeSnapshot(std.testing.allocator, &output.writer, "api.json", test_catalog);
    const generated = output.written();
    const start = std.mem.indexOf(u8, generated, "pub const non_chat_ids");
    try std.testing.expect(start != null);
    try std.testing.expectEqualStrings(
        \\pub const non_chat_ids = [_][]const u8{
        \\    "gpt-image-2",
        \\    "gpt-realtime-1",
        \\    "text-embedding-1",
        \\};
        \\pub const non_chat_families = [_][]const u8{
        \\    "gpt-realtime",
        \\    "text-embedding",
        \\};
        \\
    , generated[start.?..]);
    try std.testing.expect(std.mem.indexOf(u8, generated, "// Generated projection of api.json; same ID precedence as models_dev.zig.") != null);
    try std.testing.expect(std.mem.indexOf(u8, generated, ".id = \"gpt-image-next\", .context_window = null, .efforts = .init(.{}), .openai_listed = false") != null);
}

test "model catalog generator emits empty projection declarations" {
    var output: std.Io.Writer.Allocating = .init(std.testing.allocator);
    defer output.deinit();
    try writeSnapshot(std.testing.allocator, &output.writer, "empty.json", "{\"openai\":{\"models\":{}}}");
    try std.testing.expect(std.mem.endsWith(u8, output.written(), "pub const non_chat_ids = [_][]const u8{\n};\npub const non_chat_families = [_][]const u8{\n};\n"));
}

test "model catalog generator releases every failed projection allocation" {
    const Check = struct {
        fn run(scratch: std.mem.Allocator) !void {
            var buffer: [4096]u8 = undefined;
            var output: std.Io.Writer = .fixed(&buffer);
            try writeSnapshot(scratch, &output, "api.json", test_catalog);
        }
    };
    try std.testing.checkAllAllocationFailures(std.testing.allocator, Check.run, .{});
}
