#!/usr/bin/env python3
"""Open a PR as a draft and request Codex review; mark it ready once Codex is clean.

A draft runs only the plan job, so Codex rounds do not cancel full CI runs.
`ready` starts the selected suite on the clean head without another push.
`--ready` opens ready at once, only for the exceptions in docs/agents/landing.md
(a fix for a red main, or a PR other open PRs wait on). Merge still requires
current-candidate admission and the Codex evidence in CODING_STANDARDS.md.

  open_pr.py open --title TITLE --body-file FILE [--base main] [--ready]
  open_pr.py ready
  open_pr.py review [--pr N] (--head SHA [--findings FILE] | --fixed)

`review` posts the pr-reviewer agent's verdict as the sonnet-review-state:v1 comment that
merge_review.py and the merge hook read while Codex is out of allowance
(docs/agents/landing.md#review-evidence).
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path
from urllib.parse import quote

from conflict_alert import gh, github
from pr_overlap import branch_changes, origin_repo, overlaps, report
from pr_shape import ready_refusal as shape_ready_refusal, screens_required


def create_args(repo, title, body, base, branch, draft):
    return ["api", "-X", "POST", f"repos/{repo}/pulls", "-f", f"title={title}", "-f", f"head={branch}",
            "-f", f"base={base}", "-F", f"draft={str(draft).lower()}", "-f", f"body={body}"]


def open_refusal(local_head, pushed_head, dirty=False):
    if dirty:
        return "Commit or discard local changes first: open requires a committed head."
    if pushed_head is None:
        return "Push the branch first: it has no upstream on origin."
    if local_head != pushed_head:
        return "Push the branch first: origin does not have this commit as its head."
    return None


def ready_refusal(pr, local_head, dirty):
    if pr is None:
        return "This branch has no open PR; open one with `open_pr.py open`."
    if not pr["draft"]:
        return f"PR #{pr['number']} is already ready for review."
    if dirty:
        return "Commit or discard local changes first: ready requires a committed head."
    head = pr["head"]["sha"]
    if head != local_head:
        return (f"PR #{pr['number']}'s head on GitHub is {head[:10]}, not this checkout's "
                f"{local_head[:10]}: push the last planned commit first.")
    return None


REVIEW_FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def review_comment(head, findings=None, fixed=False):
    """The comment body for a review verdict at `head`; findings stay unresolved until `fixed`."""
    unresolved = bool(findings) and not fixed
    if fixed:
        heading, text = "## Sonnet review: findings fixed", f"Every finding above is fixed as of {head[:10]}."
    elif findings:
        heading, text = "## Sonnet review (interim, Codex unavailable)", findings.strip()
    else:
        heading, text = "## Sonnet review (interim, Codex unavailable)", "No findings."
    state = json.dumps({"commit_sha": head, "has_unresolved_findings": unresolved})
    return f"{heading}\n{text}\n<!-- sonnet-review-state:v1 {state} -->{REVIEW_FOOTER}"


def post_review(api, repo, pr, args, last_verdict):
    """Post a review verdict (or its fix) on `pr`; returns (exit code, message)."""
    if args.fixed == bool(args.head) or (args.fixed and args.findings):
        return 1, "Pass --head SHA (with --findings FILE when it found some) for a verdict, or --fixed alone."
    if args.fixed:
        last = last_verdict()
        if not last or last[0]["clean"]:
            return 1, f"PR #{pr['number']} has no unresolved review findings to mark fixed."
    try:
        findings = Path(args.findings).read_text(encoding="utf-8") if args.findings else None
    except (OSError, UnicodeError) as error:
        return 1, f"Cannot read findings: {error}"
    reviewed = args.head or pr["head"]["sha"]
    api("POST", f"repos/{repo}/issues/{pr['number']}/comments", [("body", review_comment(reviewed, findings, args.fixed))])
    return 0, f"Posted the review verdict on PR #{pr['number']} at {reviewed[:10]}."


def git(*args):
    result = subprocess.run(["git", *args], capture_output=True, text=True)
    return result.stdout.strip() if result.returncode == 0 else None


def body_refusal(pr, repo, changes=None):
    """Why admission would reject this open PR's body judged against its own base, or None."""
    base = f"origin/{pr['base']['ref']}"
    paths, _ = (changes or branch_changes)(base)
    reason = shape_ready_refusal(paths, pr["body"] or "", base=base, repo=repo, number=pr["number"])
    return f"PR #{pr['number']} would fail admission on its body: {reason}" if reason else None


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    opening = commands.add_parser("open", help="check overlap with open PRs, then open a draft PR and request Codex review")
    opening.add_argument("--title", required=True)
    opening.add_argument("--body-file", required=True)
    opening.add_argument("--base", default="main")
    opening.add_argument("--ready", action="store_true",
                         help="open ready for review (red-main fixes and PRs others wait on only)")
    opening.add_argument("--frames", help="the directory verify-rui frames printed; a UI PR opens only with its screens captured")
    commands.add_parser("ready", help="mark this branch's draft ready to run its full selected suite")
    review = commands.add_parser("review", help="post the pr-reviewer agent's verdict on a PR (default: this branch's)")
    review.add_argument("--pr", type=int)
    review.add_argument("--head", help="the head sha the reviewer reported (not the PR's head at posting time)")
    review.add_argument("--findings", help="file holding the reviewer's findings; omit when it found none")
    review.add_argument("--fixed", action="store_true", help="every finding of the last review is fixed")
    args = parser.parse_args()
    branch, head = git("branch", "--show-current"), git("rev-parse", "HEAD")
    try:
        repo = origin_repo()
        if args.command == "open":
            if refusal := open_refusal(head, git("rev-parse", "--verify", "-q", f"origin/{branch}"), bool(git("status", "--porcelain"))):
                print(refusal, file=sys.stderr)
                return 1
            try:
                body = Path(args.body_file).read_text(encoding="utf-8")
            except (OSError, UnicodeError) as error:
                print(f"Cannot read PR body: {error}", file=sys.stderr)
                return 1
            paths, removed = branch_changes(f"origin/{args.base}")
            needs_screens = screens_required(paths, base=f"origin/{args.base}")
            if refusal := shape_ready_refusal(paths, body, base=f"origin/{args.base}", frames=args.frames,
                                              needs=lambda *_, **__: needs_screens):
                print(refusal, file=sys.stderr)
                return 1
            report(overlaps(github, repo, branch, paths, removed))
            pr = json.loads(gh(*create_args(repo, args.title, body, args.base, branch, draft=not args.ready)))
            print(pr["html_url"])
            if needs_screens:
                where = args.frames or "DIR"
                print(f"UI PR: publish its screens now with verify-rui publish {where} --pr {pr['number']}; "
                      "admission stays red until then.")
            if not args.ready:
                github("POST", f"repos/{repo}/issues/{pr['number']}/comments", [("body", "@codex review")])
                print("Opened draft and requested Codex review. "
                      "Run `open_pr.py ready` after Codex review is clean to start the full selected suite.")
            else:
                print("Opened ready; Codex reviews automatically. Selected CI runs beside review.")
            print(f"Now call subscribe_pr_activity for PR #{pr['number']}: a failed required check reaches you as an event.")
            print("Merge requires current-candidate admission and clean Codex evidence; "
                  "on a draft, comment `@codex review` after each push.")
            return 0
        owner = repo.split("/")[0]
        if args.command == "review" and args.pr:
            pr = github("GET", f"repos/{repo}/pulls/{args.pr}")
        else:
            found = github("GET", f"repos/{repo}/pulls?state=open&head={quote(f'{owner}:{branch}', safe=':/')}")
            pr = found[0] if found else None
        if args.command == "review":
            if pr is None:
                print("This branch has no open PR; pass --pr N.", file=sys.stderr)
                return 1
            def last_verdict():
                from merge_review import pr_outcomes, verdicts
                return verdicts(pr_outcomes(pr["number"], repo)[0])[-1:]
            code, message = post_review(github, repo, pr, args, last_verdict)
            print(message, file=sys.stderr if code else sys.stdout)
            return code
        if refusal := ready_refusal(pr, head, bool(git("status", "--porcelain"))):
            print(refusal, file=sys.stderr)
            return 1
        if refusal := body_refusal(pr, repo):
            print(refusal, file=sys.stderr)
            return 1
        # GitHub's REST API has no ready-for-review endpoint, so this one step stays on GraphQL.
        gh("pr", "ready", str(pr["number"]), "--repo", repo)
        print(f"PR #{pr['number']} is ready; its full selected suite now runs on {head[:10]}.")
        return 0
    except (subprocess.CalledProcessError, ValueError, KeyError) as error:
        print(f"Cannot reach GitHub: {getattr(error, 'stderr', '') or error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
